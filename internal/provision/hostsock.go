package provision

import (
	"context"
	"fmt"
	"os"
	"path/filepath"

	"github.com/gschlager/silo/internal/config"
	"github.com/gschlager/silo/internal/incus"
	incuscli "github.com/lxc/incus/v7/client"
)

const (
	// hostDeviceName is the disk device that mounts the container's host
	// directory, where the silo service puts the container's sockets.
	hostDeviceName = "host"
	// HostMountPath is where that directory shows up in the container. It's on
	// the persistent rootfs: /run is a tmpfs systemd remounts during boot,
	// which would shadow a bind mount underneath it.
	HostMountPath = "/var/lib/silo/host"
	// legacyNotifyDevice is the device older silo versions used for the
	// notification socket. The host socket replaces it.
	legacyNotifyDevice = "notify"
)

// HostDir is the host directory mounted into the container at HostMountPath.
// The silo service listens there on the container's own sockets:
//
//	api.sock        notifications, opening URLs (see the service's container API)
//	ssh-agent.sock  commit signing, only the configured key, only for git
//
// Every container has its own directory, so the service knows which
// container is asking by the socket the request comes in on. The control
// socket of the service is somewhere else and never mounted.
func HostDir(container string) string {
	return filepath.Join(config.GlobalConfigDir(), "containers", container, "host")
}

// HostAPISocket is the path of the container's API socket on the host.
func HostAPISocket(container string) string {
	return filepath.Join(HostDir(container), "api.sock")
}

// HostAgentSocket is the path of the container's SSH agent socket on the host.
func HostAgentSocket(container string) string {
	return filepath.Join(HostDir(container), "ssh-agent.sock")
}

// SetupHostSocket mounts the container's host directory and installs the
// helpers that talk to the silo service through it. Safe to run on every
// `silo up`: the device hot-plugs into a running container, and the helpers
// are rewritten so they match this silo version.
func SetupHostSocket(ctx context.Context, server incuscli.InstanceServer, container string) error {
	dir := HostDir(container)
	if err := os.MkdirAll(dir, 0700); err != nil {
		return fmt.Errorf("creating %s: %w", dir, err)
	}

	inst, _, err := server.GetInstance(container)
	if err != nil {
		return fmt.Errorf("getting container %q: %w", container, err)
	}
	if dev, ok := inst.Devices[hostDeviceName]; !ok || dev["source"] != dir || dev["path"] != HostMountPath {
		if err := incus.AddDiskDevice(ctx, server, container, hostDeviceName, dir, HostMountPath, false); err != nil {
			return err
		}
	}
	if _, ok := inst.Devices[legacyNotifyDevice]; ok {
		if err := incus.RemoveDevice(ctx, server, container, legacyNotifyDevice); err != nil {
			return err
		}
		os.RemoveAll(filepath.Join(config.GlobalConfigDir(), "containers", container, "notify"))
	}

	if _, err := incus.Exec(ctx, server, container, incus.ExecOpts{}, []string{"sh", "-c", hostHelpersScript()}); err != nil {
		return fmt.Errorf("installing the silo helpers: %w", err)
	}
	return nil
}

// hostHelpers are the scripts installed in /usr/local/bin. They only use
// curl, which default_setup installs.
func hostHelpers() map[string]string {
	api := HostMountPath + "/api.sock"
	post := `curl -fsS --max-time 5 --unix-socket ` + api + ` -H 'Content-Type: text/plain' --data-binary @-`
	return map[string]string{
		// silo-notify MESSAGE: a desktop notification on the host, when
		// notifications are on and herdr isn't handling the container.
		"silo-notify": `#!/bin/sh
# Generated by silo — do not edit.
printf '%s' "$*" | ` + post + ` http://silo/v1/notify >/dev/null
`,
	}
}

func hostHelpersScript() string {
	script := "set -e\n"
	for name, content := range hostHelpers() {
		path := "/usr/local/bin/" + name
		script += fmt.Sprintf("cat > %s << 'SILO_HELPER'\n%sSILO_HELPER\nchmod 755 %s\n", path, content, path)
	}
	return script
}
