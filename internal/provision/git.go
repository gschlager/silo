// ConfigureGit sets up .gitconfig inside the container for the dev user.
func ConfigureGit(ctx context.Context, server incuscli.InstanceServer, container, username string, settings map[string]string) error {
	userOpts := incus.UserOpts("/home/"+username, "/home/"+username)

	for key, value := range settings {
		if _, err := incus.Exec(ctx, server, container, userOpts, []string{
			"git", "config", "--global", key, value,
		}); err != nil {
			return fmt.Errorf("setting git config %q: %w", key, err)
		}
	}
	return nil
}

// InstallGitHubCredentialHelper configures a git credential helper for github.com
// inside the container. The helper reads $GITHUB_TOKEN from the environment at
// git-invocation time rather than baking a token into the container, so the
// token lives only in the session/setup environment (resolved fresh per session)
// and rotating it needs no reprovision.
func InstallGitHubCredentialHelper(ctx context.Context, server incuscli.InstanceServer, container, username string) error {
	rootOpts := incus.ExecOpts{}
	userOpts := incus.UserOpts("/home/"+username, "/home/"+username)

	// Helper script. The single-quoted outer heredoc writes $GITHUB_TOKEN
	// literally; it is expanded by the shell only when git runs the helper.
	helperScript := `#!/bin/sh
# Generated by silo — do not edit
[ "$1" = get ] || exit 0
cat <<CRED
protocol=https
host=github.com
username=x-access-token
password=$GITHUB_TOKEN
CRED
`

	if _, err := incus.Exec(ctx, server, container, rootOpts, []string{
		"sh", "-c", fmt.Sprintf(
			`mkdir -p /home/%s/.silo
cat > /home/%s/.silo/git-credential-helper << 'SCRIPT'
%sSCRIPT
chmod 700 /home/%s/.silo/git-credential-helper
chown -R %s:%s /home/%s/.silo`,
			username, username, helperScript, username, username, username, username),
	}); err != nil {
		return fmt.Errorf("writing credential helper: %w", err)
	}

	// Configure git to use the helper.
	if _, err := incus.Exec(ctx, server, container, userOpts, []string{
		"git", "config", "--global",
		"credential.https://github.com.helper",
		fmt.Sprintf("/home/%s/.silo/git-credential-helper", username),
	}); err != nil {
		return fmt.Errorf("configuring credential helper: %w", err)
	}

	return nil
}

// ResolveSessionEnv resolves every credential source for a project into
// environment variables: secrets: blocks from the presets the project opted
// into, then the central secrets file, then tool credentials and git.credential
// (each overriding the last). Runs on the host; tokens are returned for passing
// as exec env and are never written to disk. The reserved "github" secret
// populates GITHUB_TOKEN and GH_TOKEN; the git helper consumes the former.
func ResolveSessionEnv(cfg *config.MergedConfig) (map[string]string, error) {
	env := map[string]string{}

	// Preset secrets are the base so a project can override an inherited
	// reference by naming it in its own secrets.yml block.
	if err := resolveSecretsInto(env, cfg.PresetSecrets, "preset secret"); err != nil {
		return nil, err
	}

	secrets, err := config.SecretsForProjects(cfg.ProjectName(), cfg.PathScopedProjectName())
	if err != nil {
		return nil, err
	}
	if err := resolveSecretsInto(env, secrets, "secret"); err != nil {
		return nil, err
	}

	tools, err := ResolveToolEnv(cfg.ContainerName, cfg.Tools)
	if err != nil {
		return nil, err
	}
	for k, v := range tools {
		env[k] = v
	}

	if cfg.GitCredential != nil {
		val, err := resolveCredential(cfg.ContainerName, cfg.GitCredential)
		if err != nil {
			return nil, fmt.Errorf("resolving git credential: %w", err)
		}
		env["GITHUB_TOKEN"] = val
	}

	return env, nil
}

// ResolveAgentEnv builds the environment an agent is launched with: the active
// mode's env block (from the global config) as the base, with the project-level
// agent env layered on top. Values are literals or op:// references, resolved
// from 1Password on the host at launch time and passed as exec env — never
// written to disk, matching how secrets are handled elsewhere.
//
// container scopes the cache for the project's own entries (see readOp);
// the mode env comes from the global config and isn't scoped.
func ResolveAgentEnv(container string, agent config.MergedAgentConfig) (map[string]string, error) {
	resolved := map[string]string{}
	if mc, ok := agent.Modes[agent.Mode]; ok {
		for k, ref := range mc.Env {
			val, err := resolveSecret(hostScope, ref)
			if err != nil {
				return nil, fmt.Errorf("resolving agent env %q: %w", k, err)
			}
			resolved[k] = val
		}
	}
	for k, ref := range agent.Env {
		val, err := resolveSecret(container, ref)
		if err != nil {
			return nil, fmt.Errorf("resolving agent env %q: %w", k, err)
		}
		resolved[k] = val
	}
	return resolved, nil
}

// resolveSecretsInto resolves each reference in secrets and adds it to env under
// its own name, applying the reserved "github" mapping. Names are visited in
// sorted order so a failure reports the same entry every run rather than
// whichever one map iteration reached first. what names the source in errors.
func resolveSecretsInto(env, secrets map[string]string, what string) error {
	names := make([]string, 0, len(secrets))
	for name := range secrets {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		val, err := resolveSecret(hostScope, secrets[name])
		if err != nil {
			return fmt.Errorf("resolving %s %q: %w", what, name, err)
		}
		if name == "github" {
			env["GITHUB_TOKEN"] = val
			env["GH_TOKEN"] = val
			continue
		}
		env[name] = val
	}
	return nil
}

// hostScope is the cache scope of references from files only the host can
// write (secrets.yml, the global config). Those are shared between projects.
// References from a project's .silo.yml are cached per container instead:
// the agent can write that file, and it mustn't get a value another project
// caused to be cached without anyone being asked.
const hostScope = ""

// resolveSecret resolves a value: a 1Password reference (op://…) is read via
// the op CLI on the host; anything else is treated as a literal.
func resolveSecret(scope, ref string) (string, error) {
	if strings.HasPrefix(ref, "op://") {
		return readOp(scope, ref)
	}
	return ref, nil
}

// SecretStore is a cache readOp asks before running op, and fills after.
type SecretStore interface {
	Get(ref svcapi.SecretRef) (string, bool)
	Put(ref svcapi.SecretRef, value string)
}

// Secrets is where readOp caches values. In the CLI it's this process's
// memory plus the silo service's cache. The service replaces it with its own
// cache, which it clears on screen lock; a second copy in this package would
// outlive that.
var Secrets SecretStore = &cliSecrets{memo: map[svcapi.SecretRef]string{}}

// cliSecrets remembers values for the rest of the process (one `silo up`
// resolves the same secrets for setup, the clone and the daemons) and asks
// the silo service's cache.
type cliSecrets struct {
	mu   sync.Mutex
	memo map[svcapi.SecretRef]string
}

func (c *cliSecrets) Get(ref svcapi.SecretRef) (string, bool) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if v, ok := c.memo[ref]; ok {
		return v, true
	}
	if svc := svcapi.Connect(); svc != nil {
		if v, ok := svc.CachedSecret(ref); ok {
			c.memo[ref] = v
			return v, true
		}
	}
	return "", false
}

func (c *cliSecrets) Put(ref svcapi.SecretRef, value string) {
	c.mu.Lock()
	c.memo[ref] = value
	c.mu.Unlock()
	if svc := svcapi.Connect(); svc != nil {
		svc.CacheSecret(ref, value)
	}
}

// opMu serializes op calls, so two lookups of the same reference don't both
// ask 1Password.
var opMu sync.Mutex

// readOp reads a 1Password reference: from the cache (see Secrets), and only
// then with the op CLI.
func readOp(scope, ref string) (string, error) {
	opMu.Lock()
	defer opMu.Unlock()
	key := svcapi.SecretRef{Ref: ref, Account: os.Getenv("OP_ACCOUNT"), Scope: scope}
	if v, ok := Secrets.Get(key); ok {
		return v, nil
	}
	out, err := exec.Command("op", "read", ref).Output()
	if err != nil {
		return "", fmt.Errorf("reading from 1Password (%s): %w", ref, err)
	}
	v := strings.TrimSpace(string(out))
	Secrets.Put(key, v)
	return v, nil
}

// resolveCredential resolves a credential from its configured source.
// This runs on the HOST, not inside the container. Credentials are set in the
// project's .silo.yml, so they're cached per container.
func resolveCredential(container string, cred *config.CredentialConfig) (string, error) {
	switch cred.Source {
	case "1password":
		if cred.Ref == "" {
			return "", fmt.Errorf("1password credential requires 'ref' field")
		}
		return readOp(container, cred.Ref)

	case "token":
		if cred.Value != "" {
			return cred.Value, nil
		}
		if cred.Env != "" {
			val := os.Getenv(cred.Env)
			if val == "" {
				return "", fmt.Errorf("environment variable %q is not set", cred.Env)
			}
			return val, nil
		}
		return "", fmt.Errorf("token credential requires 'value' or 'env' field")

	default:
		return "", fmt.Errorf("unknown credential source: %q", cred.Source)
	}
}
